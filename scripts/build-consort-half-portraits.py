"""Pack half-body extensions under their ORIGINAL portrait IDs.

Usage: python3 scripts/build-consort-half-portraits.py /path/to/generated_images
Requires Pillow. This only extracts source cells, proportionally scales them and
packs transparent atlases. It never edits faces, removes backgrounds or rewrites
the original portrait atlases. The six existing matched paintings are reused.
"""
import argparse
import importlib.util
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SPEC = importlib.util.spec_from_file_location('expanded', ROOT / 'scripts/build-expanded-portraits.py')
expanded = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(expanded)
FRAME = (448, 560)
PER_ATLAS = 12


def build(folder, metadata_only=False):
    plan = json.loads((ROOT / 'docs/consort-half-portrait-plan.json').read_text())
    frames, entries = [], []
    for batch in plan['batches']:
        filename = batch['source']
        with Image.open(folder / filename) as art:
            assert art.mode == 'RGBA' and art.getchannel('A').getextrema()[0] == 0, filename
            cols = 3 if len(batch['ids']) == 6 else 2
            ys = expanded.grid_edges(art.getchannel('A'), 2, vertical=True)
            for i, id in enumerate(batch['ids']):
                row, col = divmod(i, cols)
                strip = art.crop((0, ys[row], art.width, ys[row+1]))
                xs = expanded.grid_edges(strip.getchannel('A'), cols)
                box = (xs[col], ys[row], xs[col+1], ys[row+1])
                tile = art.crop(box)
                bounds = tile.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
                assert bounds, (filename, id)
                frame = ImageOps.contain(tile.crop(bounds), (440, 552), Image.Resampling.LANCZOS)
                offset = ((448-frame.width)//2, 560-frame.height)
                canvas = Image.new('RGBA', FRAME)
                canvas.paste(frame, offset)
                frames.append(canvas)
                entries.append({'id': id, 'source': filename, 'cell': i,
                    'crop': list(box), 'bounds': list(bounds), 'offset': list(offset),
                    'size': list(frame.size), 'head': batch.get('heads', {}).get(str(id), [56, 29, 26])})
    assert len(set(p['id'] for p in entries)) == len(entries)
    assert [p['id'] for p in entries] == plan['new']
    sheets = []
    for start in range(0, len(frames), PER_ATLAS):
        group = frames[start:start+PER_ATLAS]
        number = start//PER_ATLAS
        rows = (len(group)+3)//4
        name = f'palace-consort-half-{number+1:02}.webp'
        atlas = Image.new('RGBA', (1792, rows*560))
        for i, frame in enumerate(group):
            atlas.paste(frame, (i%4*448, i//4*560))
            entries[start+i].update({'atlas': name, 'atlasIndex': number, 'tile': i})
        output = ROOT/'assets/images'/name
        if metadata_only:
            with Image.open(output) as existing:
                assert existing.size == atlas.size, name
        else:
            atlas.save(output, 'WEBP', quality=96, method=6, exact=True)
        sheets.append({'start': 0, 'rows': rows, 'scale': 4, 'src': './assets/images/'+name+'?v=1'})
    manifest = {'frame': list(FRAME), 'columns': 4, 'portraits': entries, 'pairs': plan['paired']}
    (ROOT/'docs/consort-half-portrait-sources.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
    mapping = {p['id']: {'atlas': p['atlasIndex'], 'tile': p['tile'], 'head': p['head']} for p in entries}
    js = '// Generated by scripts/build-consort-half-portraits.py. Stable original IDs.\n'
    js += 'const CONSORT_DETAIL_SHEETS='+json.dumps(sheets, separators=(',', ':'))+';\n'
    js += 'const CONSORT_DETAIL_ART=Object.freeze('+json.dumps(mapping, separators=(',', ':'))+');\n'
    js += 'const CONSORT_DETAIL_PAIRS=Object.freeze('+json.dumps(plan['paired'], separators=(',', ':'))+');\n'
    (ROOT/'js/consort-portrait-details.js').write_text(js)
    print(f'{len(entries)} half-body extensions; {len(plan["paired"])} existing pairs; {len(sheets)} atlases')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_folder', type=Path)
    parser.add_argument('--metadata-only', action='store_true', help='Update head anchors after visual review; keep packed pixels unchanged')
    args = parser.parse_args()
    build(args.source_folder, args.metadata_only)
