const QUEEN_EMPTY_TITLE='选秀定榜 · 中宫见空册';
function queenEmptySelectionData(queen){
  return STORY_QUEEN_EMPTY_REACTIONS[storyQueenKey(queen)]||QUEEN_EMPTY_REACTIONS[queen.trait]||QUEEN_EMPTY_REACTIONS.持重;
}
function queenEmptySelectionReaction(queen,batch){
  if(!queenEmptySelectionActive()||!batch?.batch||batch.accepted?.length||S.over||!inPalace(queen))return;
  const data=queenEmptySelectionData(queen),gen=S.gen;
  const concern={mode:selectionDisposition(queen),text:data.text,quote:data.quote,batch:batch.batch,stage:'settled',turn:S.turn};
  queen.selectionConcern=concern;
  const note='本轮选秀无人留选。'+data.text+'她说：“'+data.quote+'”';
  story(queen,'【选秀定榜·中宫见空册】'+note);
  if(data.mood)cchg(queen,{mood:data.mood});

  // The automatic scene belongs to a recorded decision or a recorded month close.
  if(!PalaceActions.busy)return;
  let answered=false;
  const valid=()=>!answered&&S.gen===gen&&!S.over&&queen===empress()&&inPalace(queen);
  const answer=follow=>{
    if(!valid())return null;
    answered=true;
    const line=follow?data.reply:'陛下听了她的话，仍由礼部按定册办理离宫事宜。';
    concern.reply=line;
    if(follow){noteHaremVisit(queen);remember(queen,'care',line);cchg(queen,{aff:2});}
    story(queen,'【选秀定榜·中宫答话】'+line);
    return line;
  };
  pushEv({title:QUEEN_EMPTY_TITLE,por:queen,present:[queen],valid,
    text:'留选名册合上，这一轮谁也没有留下。皇后'+fullName(queen)+'来见你。\n'+data.text+'\n“'+data.quote+'”',
    choices:[{t:data.action,f:()=>answer(true)},{t:'听她说完，由礼部照例结案',f:()=>answer(false)}]});
}
