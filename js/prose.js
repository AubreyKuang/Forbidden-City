function proseEpigraph(ev){
  if(!ev||ev.ref||ev.poemPrelude||!proseActive())return null;
  const title=String(ev.title||'');
  const entry=PROSE_EPIGRAPHS[title]||PROSE_EPIGRAPHS[title.split(' · ')[0]];
  return entry?{line:entry[0],source:entry[1]}:null;
}
